import { execFile } from 'node:child_process'
import { createHash, randomUUID } from 'node:crypto'
import {
  chmodSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'
import { setTimeout as sleep } from 'node:timers/promises'
import { privateDir } from './local.js'

const run = promisify(execFile)
const cli = fileURLToPath(new URL('./cli.mjs', import.meta.url))
const marker = 'Generated by NativeCrew Computer Host'
const xml = (s) =>
  s.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')
const unitArg = (s) =>
  '"' + s.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replaceAll('%', '%%').replaceAll('$', '$$') + '"'
const pathEnv = [
  ...new Set([
    dirname(process.execPath),
    '/opt/homebrew/bin',
    '/usr/local/bin',
    '/usr/bin',
    '/bin',
    '/usr/sbin',
    '/sbin',
  ]),
].join(':')

export function serviceDefinition(platform, options, home = homedir()) {
  const { home: directory, relay, name, headless, noPrompts } = options
  const id = createHash('sha256').update(directory).digest('hex').slice(0, 12)
  const label = 'io.github.godbot.computer.' + id
  const entry = process.env.GODBOT_MACHINE_LAUNCHER
    ? [process.env.GODBOT_MACHINE_LAUNCHER]
    : [process.execPath, cli]
  const args = [
    ...entry,
    'start',
    '--home',
    directory,
    ...(relay ? ['--relay', relay] : []),
    ...(name ? ['--name', name] : []),
    ...(headless ? ['--headless'] : []),
    ...(noPrompts ? ['--no-prompts'] : []),
  ]
  if (args.some((arg) => /[\x00-\x1f\x7f]/.test(arg)))
    throw new Error('Invalid control character in service argument')
  if (platform === 'darwin') {
    return {
      label,
      path: join(home, 'Library/LaunchAgents', label + '.plist'),
      text:
        '<?xml version="1.0" encoding="UTF-8"?>\n<!-- ' +
        marker +
        ' -->\n<plist version="1.0"><dict>\n' +
        '<key>Label</key><string>' +
        label +
        '</string>\n<key>ProgramArguments</key><array>\n' +
        args.map((arg) => '<string>' + xml(arg) + '</string>').join('\n') +
        '\n</array>\n' +
        '<key>EnvironmentVariables</key><dict><key>PATH</key><string>' +
        xml(pathEnv) +
        '</string></dict>\n' +
        '<key>RunAtLoad</key><true/><key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>\n' +
        '<key>ThrottleInterval</key><integer>10</integer>\n</dict></plist>\n',
    }
  }
  if (platform === 'linux') {
    return {
      label: label + '.service',
      path: join(home, '.config/systemd/user', label + '.service'),
      text:
        '# ' +
        marker +
        '\n[Unit]\nDescription=NativeCrew Computer Host\nAfter=network.target\n\n[Service]\n' +
        'ExecStart=' +
        args.map(unitArg).join(' ') +
        '\nEnvironment="PATH=' +
        pathEnv +
        '"\n' +
        'UMask=0077\nRestart=on-failure\nRestartSec=10\nKillMode=mixed\nTimeoutStopSec=10\n\n[Install]\nWantedBy=default.target\n',
    }
  }
  throw new Error('NativeCrew Computer Host services support macOS and Linux')
}

export async function manageService(install, options) {
  const { label, path, text } = serviceDefinition(process.platform, options)
  if (existsSync(path) && (!lstatSync(path).isFile() || !readFileSync(path, 'utf8').includes(marker))) {
    throw new Error('An existing service file has a different owner: ' + path)
  }
  if (install) {
    privateDir(options.home)
    if (!options.relay && !existsSync(join(options.home, 'identity.json')))
      throw new Error('Specify --relay on the first install')
    mkdirSync(dirname(path), { recursive: true })
    const temp = path + '.' + randomUUID()
    writeFileSync(temp, text, { mode: 0o600, flag: 'wx' })
    renameSync(temp, path)
    chmodSync(path, 0o600)
  } else if (!existsSync(path)) return
  if (process.platform === 'darwin') {
    const domain = 'gui/' + process.getuid()
    const target = domain + '/' + label
    let loaded = true
    try {
      await run('/bin/launchctl', ['print', target])
    } catch {
      loaded = false
    }
    if (loaded) await run('/bin/launchctl', ['bootout', target])
    if (install) {
      // On macOS bootout can return before launchd has released the label.
      // Retry only that transient replacement race. Invalid first installs
      // report their real error straight away.
      for (let attempt = 0; ; attempt++) {
        try {
          await run('/bin/launchctl', ['bootstrap', domain, path])
          break
        } catch (err) {
          if (!loaded || attempt >= 6 || !String(err.stderr).includes('Input/output error')) throw err
          await sleep(100 * (attempt + 1))
        }
      }
    }
  } else {
    if (install) {
      await run('systemctl', ['--user', 'daemon-reload'])
      await run('systemctl', ['--user', 'enable', label])
      await run('systemctl', ['--user', 'restart', label])
    } else await run('systemctl', ['--user', 'disable', '--now', label])
  }
  if (!install) {
    unlinkSync(path)
    if (process.platform === 'linux') await run('systemctl', ['--user', 'daemon-reload'])
  }
  console.log((install ? 'Installed ' : 'Removed ') + label)
}
